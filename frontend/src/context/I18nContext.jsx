const I18nContext = createContext(null);

const getValue = (obj, path) => {
  return path.split('.').reduce((acc, key) => (acc && acc[key] !== undefined ? acc[key] : undefined), obj);
};

export const I18nProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    const stored = localStorage.getItem('isosmart_language');
    return SUPPORTED_LANGUAGES.includes(stored) ? stored : DEFAULT_LANGUAGE;
  });

  const setLanguage = useCallback((nextLanguage) => {
    const normalized = SUPPORTED_LANGUAGES.includes(nextLanguage) ? nextLanguage : DEFAULT_LANGUAGE;
    localStorage.setItem('isosmart_language', normalized);
    setLanguageState(normalized);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback(
    (key, fallback = key) => {
      if (typeof key === 'string' && key.startsWith('literals.')) {
        const literalKey = key.slice('literals.'.length);
        const translatedLiteral = LITERAL_TRANSLATIONS[language]?.[literalKey];
        if (translatedLiteral !== undefined) return translatedLiteral;
        if (language === DEFAULT_LANGUAGE) return literalKey;
        return translateLiteralFallback(literalKey, language);
      }

      const primary = getValue(MESSAGES[language], key);
      if (primary !== undefined) return primary;
      const defaultValue = getValue(MESSAGES[DEFAULT_LANGUAGE], key);
      return defaultValue !== undefined ? defaultValue : fallback;
    },
    [language]
  );

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      supportedLanguages: SUPPORTED_LANGUAGES,
      t,
    }),
    [language, setLanguage, t]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n debe usarse dentro de I18nProvider');
  }
  return context;
};
